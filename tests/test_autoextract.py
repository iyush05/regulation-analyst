def facts(result):
    found = {}
    for candidate in result["candidates"]:
        evidence = {e["id"]: e for e in candidate["bundle"]["evidence"]}
        for f in candidate["bundle"]["facts"]:
            key = (f["metric"], f["fiscal_year"], f["scope"])
            assert key not in found, f"{key} mapped twice"
            found[key] = (f, evidence[f["evidence_id"]])
    return found


